export const getTopicsForSubject = (subjectName) => {
  if (!subjectName) {
    return [
      "Общая теория",
      "Практические задачи",
      "Тестирование",
    ];
  }
  const foundKey = Object.keys(curriculumProgram).find(
    (key) =>
      subjectName.toLowerCase().includes(key.toLowerCase()) ||
      key.toLowerCase().includes(subjectName.toLowerCase())
  );

  const list = curriculumProgram[foundKey];
  if (!list) {
    return [
      "Общая теория",
      "Практические задачи",
      "Тестирование",
    ];
  }
  return list.map(item => item.name);
};

