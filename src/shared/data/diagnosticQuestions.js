// Main selection function for diagnostic test questions
export const getDiagnosticQuestions = (profileCombo, isOrientationTrack = false) => {
  // 1. Orientation Track for 9-10th grade
  if (isOrientationTrack) {
    const pool = [];
    // Compulsory (5 questions each)
    const comp1 = diagnosticQuestionPool["История Казахстана"] || [];
    const comp2 = diagnosticQuestionPool["Математическая грамотность"] || [];
    const comp3 = diagnosticQuestionPool["Грамотность чтения"] || [];

    pool.push(...comp1.slice(0, 5));
    pool.push(...comp2.slice(0, 5));
    pool.push(...comp3.slice(0, 5));

    // Orientation blocks (3 questions total, 1 per main field)
    // Technical
    const mathPool = diagnosticQuestionPool["Математика"] || [];
    if (mathPool.length > 0) pool.push(mathPool[0]);
    // Science
    const bioPool = diagnosticQuestionPool["Биология"] || [];
    if (bioPool.length > 0) pool.push(bioPool[0]);
    // Humanities
    const histPool = diagnosticQuestionPool["Всемирная история"] || [];
    if (histPool.length > 0) pool.push(histPool[0]);

    return pool;
  }

  // 2. Main Diagnostic for 11th grade (or standard profile diagnostic)
  const profileSubjects = (profileCombo && profileCombo.includes("–")) 
    ? profileCombo.split("–").map(s => s.trim()) 
    : (profileCombo && profileCombo.includes("-")) 
      ? profileCombo.split("-").map(s => s.trim()) 
      : profileCombo === "Творческий экзамен" 
        ? ["Творческий экзамен 1", "Творческий экзамен 2"]
        : [profileCombo || "Математика", "Физика"]; // fallback

  const pool = [];

  // Compulsory subjects (6 questions each)
  const comp1 = diagnosticQuestionPool["История Казахстана"] || [];
  const comp2 = diagnosticQuestionPool["Математическая грамотность"] || [];
  const comp3 = diagnosticQuestionPool["Грамотность чтения"] || [];

  pool.push(...comp1.slice(0, 6));
  pool.push(...comp2.slice(0, 6));
  pool.push(...comp3.slice(0, 6));

  // Profile subjects (15 questions each)
  const prof1 = diagnosticQuestionPool[profileSubjects[0]] || [];
  const prof2 = diagnosticQuestionPool[profileSubjects[1]] || [];

  pool.push(...prof1.slice(0, 15));
  pool.push(...prof2.slice(0, 15));

  return pool;
};
